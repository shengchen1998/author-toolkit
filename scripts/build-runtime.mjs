#!/usr/bin/env node

import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const defaultOutput = path.join(
  root,
  "skills",
  "setup-author-toolkit",
  "assets",
  "runtime",
);
const args = process.argv.slice(2);
const check = args[0] === "--check";

if ((!check && args.length > 0) || (check && args.length > 2)) {
  console.error("Usage: node scripts/build-runtime.mjs [--check [RUNTIME_DIRECTORY]]");
  process.exitCode = 2;
} else {
  const output = check && args[1] ? path.resolve(args[1]) : defaultOutput;
  const result = await build({
    entryPoints: [
      path.join(root, "scripts", "validate.mjs"),
      path.join(root, "scripts", "author-project.mjs"),
    ],
    outdir: output,
    outExtension: { ".js": ".mjs" },
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node22",
    legalComments: "eof",
    logLevel: "warning",
    write: !check,
    banner: {
      js: `// Generated by scripts/build-runtime.mjs; do not edit.\nglobalThis[Symbol.for("author-toolkit.packaged-references")] = new URL("../references/", import.meta.url);`,
    },
  });

  if (check) {
    let failures = 0;
    for (const generated of result.outputFiles) {
      let actual;
      try {
        actual = await readFile(generated.path);
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
        failures += 1;
        console.error(`missing generated runtime artifact: ${generated.path}`);
        continue;
      }
      if (!actual.equals(generated.contents)) {
        failures += 1;
        console.error(`stale generated runtime artifact differs from source: ${generated.path}`);
      }
    }
    if (failures > 0) process.exitCode = 1;
    else console.log("Generated runtime artifacts are current.");
  }
}
